// Writes src/content/country-currencies.ts: each country's currency in use
// today, from Unicode CLDR (the data browsers' own Intl APIs are built on).
// Run with `npm run currencies` to refresh after a currency change.
import { writeFile } from "node:fs/promises";

const CLDR = "https://cdn.jsdelivr.net/npm/cldr-core@47/supplemental/currencyData.json";
const res = await fetch(CLDR);
if (!res.ok) throw new Error(`CLDR download failed: ${res.status}`);
const regions = (await res.json()).supplemental.currencyData.region;
const inUse = new Set(Intl.supportedValuesOf("currency"));

const map = {};
for (const [region, list] of Object.entries(regions)) {
  if (!/^[A-Z]{2}$/.test(region)) continue;
  // Legal tender still in use (no end date); the most recently introduced wins.
  const current = list
    .flatMap((entry) => Object.entries(entry))
    .filter(([code, v]) => !v._to && v._tender !== "false" && inUse.has(code))
    .sort((a, b) => (a[1]._from ?? "").localeCompare(b[1]._from ?? ""))
    .at(-1);
  if (current) map[region] = current[0];
}

const body = Object.entries(map)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([r, c]) => `  ${r}: "${c}",`)
  .join("\n");
await writeFile(
  new URL("../src/content/country-currencies.ts", import.meta.url),
  `// Generated by scripts/country-currencies.mjs from Unicode CLDR (${CLDR}).
// Do not edit by hand: run \`npm run currencies\`.
// ISO 3166 country code → the ISO 4217 currency in use there.
export const countryCurrencies: Record<string, string> = {
${body}
};
`,
);
console.log(`${Object.keys(map).length} countries`);
